package lin.bean.usePlan

/**
 * 使用阶段只表达“默认顺序”，不能表达强制关系。
 * 强制先后顺序要放到 [UseConstraint]。
 *
 * **命名原则（Q-032，2026-08-30 改名）**：阶段名一律用**出牌时序**命名，禁止照搬用途语义。
 *
 * 原命名（`RESOURCE`/`CLEAR`/`DEFEND`/`END`）是从用途标签倒推的，导致语义错位：
 * 例如「过牌牌」被放进名叫 `CLEAR`（解场）的阶段，读起来自相矛盾。
 * 阶段本质是**出牌时序位置**（引擎侧仅被用于排序，见 `UsePlanOrderer`），
 * 与「这张牌是干什么用的」是两件事，不应共用一套词汇。
 *
 * 时序命名后，任何用途的牌放进任何阶段都不违和，阶段只回答「大概什么时候出」。
 *
 * **先后可配**：声明顺序仅为默认值，实际次序由 `engine.properties` 的 `stage.order` 决定
 * （见 `EngineConfig.stageOrder`），可为不同卡组配置不同波段顺序。
 */
enum class UseStage {
    /** 最先出：资源类（硬币等）。 */
    FIRST,

    /** 铺垫期：早期布局（成长、铺场等）。 */
    SETUP,

    /** 中段：场面处理与信息获取（解场、过牌等）。 */
    MID,

    /** 中后段：响应威胁（保命、防御等）。 */
    LATE,

    /** 常规：无特殊时序要求（默认落脚点，未配标签的牌在此）。 */
    GENERAL,

    /** 压轴：最后出。语义收窄后无标签默认映射，需靠 stageOverride / conditionalStage 显式指定。 */
    LAST
}
